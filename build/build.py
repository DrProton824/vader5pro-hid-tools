#
# build/build.py
# Build both executables with PyInstaller.
#

"""
Run from the repo root:
    python build/build.py

Outputs land in dist/VaderMapper/
  VaderService.exe   – no console window, no UAC elevation, custom icon
  VaderConfig.exe    – windowed GUI, custom icon
  config.json        – default config copied next to executables
  assets/            – single shared folder: service tray icons plus every
                       GUI asset (controller art, hit zones, images, fonts),
                       merged flat next to both exes

Version stamping
────────────────
VERSION_FILE (service/version.py) is overwritten with the BUILD_VERSION env
var just before building, then restored afterwards so the repo's working tree
stays clean. Falls back to "dev" if BUILD_VERSION is unset (local builds).

Asset layout
────────────
Service icons and GUI assets land in the same flat assets/ folder next to both
exes — matching service/main.py and gui frozen-mode path lookups. One shared
folder, not assets/ + gui/assets/.

Excluded modules
────────────────
legacy_hid_reader is excluded from the service build — it's a reference
implementation only, replaced by rawinput_reader.RawInputReaderThread.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import os

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist" / "VaderMapper"

SERVICE_ROOT = ROOT / "service"
SERVICE_ASSETS = SERVICE_ROOT / "assets"
SERVICE_ICON = SERVICE_ASSETS / "icons" / "service_connected.ico"
SERVICE_ICON_DISCONNECTED = SERVICE_ASSETS / "icons" / "service_disconnected.ico"

GUI_ROOT = ROOT / "gui"
GUI_ASSETS = GUI_ROOT / "assets"
CONFIG_ICON = GUI_ASSETS / "icons" / "config.ico"

# Stamped with the build version just before building, then restored -
# see _write_version_file / _restore_version_file below.
VERSION_FILE = SERVICE_ROOT / "version.py"


def _get_version() -> str:
    """
    Read the version to build from the BUILD_VERSION env var (set by the
    GitHub Actions workflow_dispatch input). Falls back to "dev" for
    local builds so nothing breaks if it's unset.
    """
    return os.environ.get("BUILD_VERSION", "dev").strip() or "dev"


def _write_version_file(version: str) -> str:
    """Stamp service/version.py with the build version; return its previous contents so the caller can restore them afterwards."""
    original = VERSION_FILE.read_text(encoding="utf-8")
    VERSION_FILE.write_text(
        '"""Auto-generated by build/build.py - do not edit by hand."""\n'
        f'VERSION = "{version}"\n',
        encoding="utf-8",
    )
    return original


def _restore_version_file(original_text: str) -> None:
    VERSION_FILE.write_text(original_text, encoding="utf-8")


def package_release(version: str) -> Path:
    """Zip the built dist/VaderMapper folder into dist/VaderMapper-v<version>.zip."""
    archive_base = ROOT / "dist" / f"VaderMapper-v{version}"
    archive_path = shutil.make_archive(str(archive_base), "zip", root_dir=DIST)
    return Path(archive_path)


def _base_args(name: str, entry: Path, icon: Path | None = None, extra: list[str] | None = None) -> list[str]:
    """PyInstaller flags shared by both executables."""
    args = [
        sys.executable, "-m", "PyInstaller",
        "--onefile",
        "--noconsole",
        "--name", name,
        "--distpath", str(DIST),
        "--workpath", str(ROOT / "build" / "work" / name),
        "--specpath", str(ROOT / "build"),
        "--collect-all", "hid",
        "--exclude-module", "service.hid_interface.legacy_hid_reader",
    ]

    if icon and icon.exists():
        args += ["--icon", str(icon)]
    else:
        print(f"  (icon not found at {icon} - run tools/generate_icons.py first "
              f"for a custom icon; building with the default one for now)")

    if extra:
        args += extra
    args.append(str(entry))
    return args


def run(cmd: list[str]) -> None:
    print("\n>", " ".join(str(c) for c in cmd))
    result = subprocess.run(cmd, cwd=ROOT)
    if result.returncode != 0:
        sys.exit(result.returncode)


def build_service() -> None:
    run(_base_args(
        "VaderService",
        SERVICE_ROOT / "main.py",
        SERVICE_ICON,
    ))


def build_config_gui() -> None:
    run(_base_args(
        "VaderConfig",
        GUI_ROOT / "MainPage.py",
        CONFIG_ICON,
        extra=[
            "--collect-all", "customtkinter",
            "--collect-all", "PIL",
            "--collect-all", "keyboard",
        ],
    ))


def copy_runtime_files() -> None:
    DIST.mkdir(parents=True, exist_ok=True)

    # Service icons and GUI assets land in the SAME flat assets/ folder
    # next to both exes - matches service/main.py's and gui/scripts/
    # mapping.py's/device.py's frozen-mode lookups, and the CWD-relative
    # 'assets/...' paths CTkMaker bakes into MainPage.py (see its
    # sys.frozen chdir). One shared folder, not assets/ + gui/assets/.
    dest_assets = DIST / "assets"
    if dest_assets.exists():
        shutil.rmtree(dest_assets)
    if SERVICE_ASSETS.exists():
        shutil.copytree(SERVICE_ASSETS, dest_assets, dirs_exist_ok=True)
    if GUI_ASSETS.exists():
        shutil.copytree(GUI_ASSETS, dest_assets, dirs_exist_ok=True)


def main() -> None:
    version = _get_version()
    print(f"Building version: {version}")

    original_version_file = _write_version_file(version)
    try:
        build_service()
        build_config_gui()
        copy_runtime_files()
        archive_path = package_release(version)
    finally:
        # Always restore, even if the build fails, so a local build
        # never leaves the repo's version.py stamped with a stray value.
        _restore_version_file(original_version_file)

    print(f"\nBuild complete -> {DIST}")
    print(f"Release archive -> {archive_path}")


if __name__ == "__main__":
    main()
