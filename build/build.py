"""
Build both executables with PyInstaller.

Run from the repo root:
    python build/build.py

If assets/icons/*.ico don't exist yet, generate them first:
    pip install pillow
    python tools/generate_icons.py

Outputs land in  dist/VaderMapper/
  VaderService.exe   – no console window, no UAC elevation, custom icon
  VaderConfig.exe    – windowed GUI, custom icon
  config.json        – default config copied next to executables
  assets/            – SVG, icons, and any other runtime assets
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import os

ROOT   = Path(__file__).resolve().parent.parent
DIST   = ROOT / "dist" / "VaderMapper"
ASSETS = ROOT / "assets"
CONFIG = ROOT / "config.json"

SERVICE_ICON = ASSETS / "icons" / "service_connected.ico"
SERVICE_ICON_DISCONNECTED = ASSETS / "icons" / "service_disconnected.ico"
CONFIG_ICON  = ASSETS / "icons" / "config.ico"

# Stamped with the build version just before building, then restored -
# see _write_version_file / _restore_version_file below.
VERSION_FILE = ROOT / "src" / "shared" / "version.py"


def _get_version() -> str:
    """
    Read the version to build from the BUILD_VERSION env var (set by the
    GitHub Actions workflow_dispatch input). Falls back to "dev" for
    local builds so nothing breaks if it's unset.
    """
    return os.environ.get("BUILD_VERSION", "dev").strip() or "dev"


def _write_version_file(version: str) -> str:
    """Stamp src/shared/version.py with the build version; return its previous contents so the caller can restore them afterwards."""
    original = VERSION_FILE.read_text(encoding="utf-8")
    VERSION_FILE.write_text(
        '"""Auto-generated by build/build.py - do not edit by hand."""\n'
        f'VERSION = "{version}"\n',
        encoding="utf-8",
    )
    return original


def _restore_version_file(original_text: str) -> None:
    VERSION_FILE.write_text(original_text, encoding="utf-8")


def package_release(version: str) -> Path:
    """Zip the built dist/VaderMapper folder into dist/VaderMapper-v<version>.zip."""
    archive_base = ROOT / "dist" / f"VaderMapper-v{version}"
    archive_path = shutil.make_archive(str(archive_base), "zip", root_dir=DIST)
    return Path(archive_path)

def _base_args(name: str, entry: Path, icon: Path | None = None, extra: list[str] | None = None) -> list[str]:
    """PyInstaller flags shared by both executables."""
    args = [
        sys.executable, "-m", "PyInstaller",
        "--onefile",
        "--noconsole",
        "--name", name,
        "--distpath", str(DIST),
        "--workpath", str(ROOT / "build" / "work" / name),
        "--specpath", str(ROOT / "build"),
        "--collect-all", "hid",
        "--exclude-module", "src.shared.legacy_hid_reader",
    ]

    if icon and icon.exists():
        args += ["--icon", str(icon)]
    else:
        print(f"  (icon not found at {icon} - run tools/generate_icons.py first "
              f"for a custom icon; building with the default one for now)")

    if extra:
        args += extra
    args.append(str(entry))
    return args


def run(cmd: list[str]) -> None:
    print("\n>", " ".join(str(c) for c in cmd))
    result = subprocess.run(cmd, cwd=ROOT)
    if result.returncode != 0:
        sys.exit(result.returncode)
        

def build_service() -> None:
    run(_base_args(
        "VaderService",
        ROOT / "src" / "service" / "main.py",
        SERVICE_ICON,
    ))


def build_config_gui() -> None:
    run(_base_args(
        "VaderConfig",
        ROOT / "src" / "config_gui" / "main.py",
        CONFIG_ICON,
        extra=["--collect-all", "customtkinter"],
    ))


def copy_runtime_files() -> None:
    DIST.mkdir(parents=True, exist_ok=True)

    # Only copy default config if the user does not already have one
    dest_config = DIST / "config.json"
    if not dest_config.exists():
        shutil.copy2(CONFIG, dest_config)

    # Always refresh assets
    dest_assets = DIST / "assets"
    if ASSETS.exists():
        if dest_assets.exists():
            shutil.rmtree(dest_assets)
        shutil.copytree(ASSETS, dest_assets)


def main() -> None:
    version = _get_version()
    print(f"Building version: {version}")

    original_version_file = _write_version_file(version)
    try:
        build_service()
        build_config_gui()
        copy_runtime_files()
        archive_path = package_release(version)
    finally:
        # Always restore, even if the build fails, so a local build
        # never leaves the repo's version.py stamped with a stray value.
        _restore_version_file(original_version_file)

    print(f"\nBuild complete -> {DIST}")
    print(f"Release archive -> {archive_path}")


if __name__ == "__main__":
    main()
